    peft_config = LoraConfig(
        r=CONFIG["qlora_r"],
        lora_alpha=CONFIG["qlora_alpha"],
        target_modules=CONFIG["qlora_target_modules"],
        lora_dropout=0.05,
        bias="none",
        task_type="CAUSAL_LM"
    )
    
    peft_model = get_peft_model(qlora_model, peft_config)
